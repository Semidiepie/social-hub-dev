import React, { useCallback, useEffect, useState } from "react";
import { ActivityIndicator, Alert, ScrollView, StyleSheet, Text, TextInput, TouchableOpacity, View } from "react-native";
import { Stack } from "expo-router";
import { api } from "../../src/api/client";
import { colors, spacing } from "../../src/theme";

/**
 * Studio Curated accounts, matching the web page (frontend/src/pages/AdminCurate.jsx):
 * GET /admin/curated-clips, POST /admin/curated-accounts
 * {display_name, username, avatar_url}, POST /admin/sage-clip {query},
 * POST /admin/curated-clips {video_url, thumbnail_url, caption}.
 * Clip file upload (Cloudinary) cannot be reproduced in the app, so clips
 * are listed and Sage clips can be generated by query; account adding is by
 * display name / username / avatar URL.
 */
export default function AdminCurate() {
  const [clips, setClips] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [displayName, setDisplayName] = useState("");
  const [username, setUsername] = useState("");
  const [avatarUrl, setAvatarUrl] = useState("");
  const [query, setQuery] = useState("");
  const [busy, setBusy] = useState(false);
  const load = useCallback(async () => {
    setLoading(true);
    try { const res = await api.get<any>("/admin/curated-clips"); setClips(Array.isArray(res) ? res : res.clips || res.items || []); } catch { setClips([]); } finally { setLoading(false); }
  }, []);
  useEffect(() => { load(); }, [load]);
  const addAccount = async () => {
    if (!displayName.trim()) { Alert.alert("Curated accounts", "Enter a display name first."); return; }
    setBusy(true);
    try { await api.post("/admin/curated-accounts", { display_name: displayName.trim(), username: username.trim() || null, avatar_url: avatarUrl.trim() || null }); setDisplayName(""); setUsername(""); setAvatarUrl(""); Alert.alert("Curated accounts", "Account added."); } catch (e: any) { Alert.alert("Curated accounts", e?.message || "Failed"); } finally { setBusy(false); }
  };
  const sageClip = async () => {
    setBusy(true);
    try { await api.post("/admin/sage-clip", { query: query.trim() || displayName.trim() || "trending" }); await load(); Alert.alert("Sage clip", "Sage clip generated."); } catch (e: any) { Alert.alert("Sage clip", e?.message || "Failed"); } finally { setBusy(false); }
  };
  return (
    <View style={styles.root}>
      <Stack.Screen options={{ title: "Curated accounts" }} />
      <ScrollView style={styles.scroll} contentContainerStyle={{ paddingBottom: 32 }}>
        <Text style={styles.section}>Add a curated account</Text>
        <TextInput style={styles.input} placeholder="Display name" placeholderTextColor={colors.textMuted} value={displayName} onChangeText={setDisplayName} testID="admin-curate-display-name" />
        <TextInput style={styles.input} placeholder="Username (optional)" placeholderTextColor={colors.textMuted} value={username} onChangeText={setUsername} autoCapitalize="none" testID="admin-curate-username" />
        <TextInput style={styles.input} placeholder="Avatar URL (optional)" placeholderTextColor={colors.textMuted} value={avatarUrl} onChangeText={setAvatarUrl} autoCapitalize="none" testID="admin-curate-avatar" />
        <TouchableOpacity style={styles.btn} onPress={addAccount} disabled={busy}><Text style={styles.btnText}>Add curated account</Text></TouchableOpacity>
        <Text style={styles.section}>Generate a Sage clip</Text>
        <TextInput style={styles.input} placeholder="Category or query (e.g. trending)" placeholderTextColor={colors.textMuted} value={query} onChangeText={setQuery} testID="admin-curate-query" />
        <TouchableOpacity style={styles.btn} onPress={sageClip} disabled={busy}><Text style={styles.btnText}>Generate Sage clip</Text></TouchableOpacity>
        <Text style={styles.note}>Clip file upload is done on the web (Cloudinary). The app lists the curated clips below.</Text>
        <Text style={styles.section}>Curated clips</Text>
        {loading ? <ActivityIndicator color={colors.primary} /> : clips.length === 0 ? <Text style={styles.empty}>No curated clips yet.</Text> : clips.map((c: any, i: number) => (
          <View key={c.id || i} style={styles.card}><Text style={styles.cardText}>{c.caption || c.title || c.video_url || "Clip"}</Text>{c.video_url ? <Text style={styles.cardMeta}>{c.video_url}</Text> : null}</View>
        ))}
      </ScrollView>
    </View>
  );
}
const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: colors.bg, padding: spacing.lg },
  scroll: { flex: 1 },
  section: { color: colors.textPrimary, fontSize: 16, fontWeight: "700", marginTop: 14, marginBottom: 8 },
  input: { backgroundColor: colors.surface, borderWidth: 1, borderColor: colors.border, borderRadius: 10, color: colors.textPrimary, paddingHorizontal: 12, paddingVertical: 10, fontSize: 15, marginBottom: 8 },
  btn: { backgroundColor: colors.primary, borderRadius: 10, paddingVertical: 11, alignItems: "center", marginBottom: 8 },
  btnText: { color: "#FFFFFF", fontWeight: "700" },
  note: { color: colors.textSecondary, fontSize: 13, marginTop: 4 },
  card: { backgroundColor: colors.surface, borderWidth: 1, borderColor: colors.border, borderRadius: 10, padding: 12, marginBottom: 8 },
  cardText: { color: colors.textPrimary, fontSize: 14, fontWeight: "600" },
  cardMeta: { color: colors.textSecondary, fontSize: 12, marginTop: 4 },
  empty: { color: colors.textSecondary, fontSize: 14 },
});
